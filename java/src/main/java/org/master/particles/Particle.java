package org.master.particles;

final class Particle {
    double x, y, z, vx, vy, vz, fx, fy, fz;

    Particle(double x, double y, double z, double vx, double vy, double vz) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.vx = vx;
        this.vy = vy;
        this.vz = vz;
    }
}
